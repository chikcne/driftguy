import assert from "node:assert/strict";
import { DirectionalLight, NullEngine, Scene, ShadowGenerator, StandardMaterial, Vector3 } from "@babylonjs/core";
import { BARREL_SCRAP_PIECES, PickupSystem, SCRAP_XP_MULTIPLIER } from "../src/combat";
import { CarBody } from "../src/vehicle";
import { World, type Collider } from "../src/world";

const engine = new NullEngine();
const scene = new Scene(engine);
const material = new StandardMaterial("test", scene);
const light = new DirectionalLight("sun", new Vector3(0, -1, 0), scene);
const world = new World(scene, material, new ShadowGenerator(64, light));
const pickups = new PickupSystem(scene, material);
// Inspect generated placements so this check follows the real world generation path.
const state = world as unknown as { colliderGrid: Map<number, Collider[]> };
world.update(100, 100);
const barrel = [...state.colliderGrid.values()].flat().find((collider) => collider.barrel);
assert.ok(barrel, "world should generate barrels");
assert.ok(barrel.r >= 0.45 * Math.cbrt(3) && barrel.r <= 0.495 * Math.cbrt(3), "barrel hit radius must scale with its volume");
const x = barrel.x;
const z = barrel.z;
let rewards = 0;
const drop = (bx: number, bz: number): void => {
  rewards++;
  pickups.drop("scrap", bx, bz, BARREL_SCRAP_PIECES, 1);
};
const contact = { hit: false, nx: 0, nz: 0 };
assert.ok(world.resolve({ x: x + 0.01, z }, 0.01, contact).hit, "intact barrel should collide");
assert.equal(world.breakBarrels(x, z, 0.01, drop), true);
assert.equal(rewards, 1, "a barrel should award its contents once");
assert.equal(world.breakBarrels(x, z, 0.01, drop), false);
assert.equal(world.resolve({ x: x + 0.01, z }, 0.01, contact).hit, false, "broken barrel must stop colliding");
const car = new CarBody();
car.x = x;
car.z = z;
let xp = 0;
pickups.update(0, car, 10, (kind, value) => {
  assert.equal(kind, "scrap");
  xp += value * SCRAP_XP_MULTIPLIER;
});
assert.equal(xp, 12, "four scraps should award twelve XP");
world.update(x + 3000, z + 3000);
world.update(x, z);
assert.equal(world.breakBarrels(x, z, 0.01, drop), false, "broken barrels must stay broken after chunk reload");
world.reset();
world.update(x, z);
assert.equal(world.breakBarrels(x, z, 0.01, drop), true, "a new run must restore barrels");
assert.equal(rewards, 2);
scene.dispose();
engine.dispose();
console.log("Barrel checks passed: scaled hitbox, single payout, 12 XP, collision removal, chunk persistence, and reset.");
